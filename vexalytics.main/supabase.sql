-- ============ Vexalytics accounts, plans, website pixel ============
create table if not exists accounts (
  id bigint generated by default as identity (start with 100) primary key,
  email text not null unique, name text, pw text not null, lang text default 'en',
  plan_id int, plan_interval text, plan_status text not null default 'trial', plan_until timestamptz,
  suspended boolean not null default false, created_at timestamptz default now()
);
create table if not exists plans (
  id int primary key, name text not null, price_month int not null, price_year int not null, currency text default 'DZD',
  max_sites int not null default 1, platforms int not null default 3, ai boolean not null default false,
  sort int default 0, active boolean not null default true
);
create table if not exists plan_requests (
  id bigint generated always as identity primary key, account_id bigint not null, plan_id int not null,
  interval text not null default 'month', status text not null default 'pending', created_at timestamptz default now()
);
create table if not exists px_sites (
  id bigint generated always as identity primary key, account_id bigint not null, name text, domain text,
  key text not null unique, created_at timestamptz default now()
);
create table if not exists px_events (
  id bigint generated always as identity primary key, site_id bigint not null, t timestamptz default now(),
  type text not null, path text, ref text, sid text, load_ms int, val numeric, cur text, err text
);
create index if not exists px_events_site_t on px_events (site_id, t desc);
alter table accounts enable row level security; alter table plans enable row level security;
alter table plan_requests enable row level security; alter table px_sites enable row level security; alter table px_events enable row level security;
